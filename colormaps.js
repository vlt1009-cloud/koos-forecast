function reverse(stops) {
    return stops.map(s => [1 - s[0], s[1], s[2], s[3]]).reverse();
}
STOPS.rdbu_r = reverse(STOPS.rdbu);

const CACHE = new Map();

/** 256×4 RGBA LUT. 0번 칸은 색칠판에서 안 쓴다 (코드 0 = 결측이라 셰이더가
    버린다). */
export function lut(name) {
    let a = CACHE.get(name);
    if (a) return a;
    const st = STOPS[name] || STOPS.jet;
    a = new Uint8Array(256 * 4);
    let k = 0;
    for (let i = 0; i < 256; i++) {
        const t = i / 255;
        while (k < st.length - 2 && t > st[k + 1][0]) k++;
        const p = st[k], q = st[k + 1];
        const f = q[0] === p[0] ? 0 : (t - p[0]) / (q[0] - p[0]);
        const g = f < 0 ? 0 : f > 1 ? 1 : f;
        a[i * 4] = p[1] + (q[1] - p[1]) * g;
        a[i * 4 + 1] = p[2] + (q[2] - p[2]) * g;
        a[i * 4 + 2] = p[3] + (q[3] - p[3]) * g;
        a[i * 4 + 3] = 255;
    }
    CACHE.set(name, a);
    return a;
}

/** 범례용 CSS 그라디언트. LUT 를 그대로 읽으므로 지도와 반드시 같은 색이다. */
export function gradient(name, n = 24) {
    const a = lut(name), out = [];
    for (let i = 0; i < n; i++) {
        const j = Math.round(i / (n - 1) * 255) * 4;
        out.push(`rgb(${a[j]},${a[j + 1]},${a[j + 2]}) `
                 + `${(100 * i / (n - 1)).toFixed(1)}%`);
    }
    return `linear-gradient(to right,${out.join(",")})`;
}

/** 값 하나의 색 (관측 점 찍을 때). t 는 0~1. */
export function color(name, t) {
    const a = lut(name);
    const i = Math.max(0, Math.min(255, Math.round(t * 255))) * 4;
    return `rgb(${a[i]},${a[i + 1]},${a[i + 2]})`;
}
